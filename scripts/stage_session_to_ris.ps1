<#
.SYNOPSIS
    Stage one session from the archive share to RIS storage, including the probe
    map -- which is the piece most likely to be forgotten.

.DESCRIPTION
    Kilosort4 on the node needs five things, and only the first is obvious:

      1. <sid>.probe1.dat          the recording            ~250-370 GiB
      2. <sid>_custom_neuropixels_map.json   the probe map  a few hundred KiB
      3. <sid>.channelmap_probe1.dat         the map's SOURCE      < 1 MiB
      4. <sid>.timestamps.dat      needed later for sync    ~2 GiB
      5. the six dio_Controller_Din{1..6}.dat files         small

    Item 2 is generated by make_probe_map.py, which imports the Trodes python
    reader from a local Trodes installation. That reader does not exist on the
    compute node, so **the map must be generated here, on Windows, and copied
    across**. This script does that in the right order and refuses to copy
    anything if the map step failed. Item 3 travels too, so the map can be
    regenerated or audited later without coming back to this PC.

    Nothing is deleted. Nothing on the archive is written to.

.PARAMETER SessionId
    e.g. 20261021_111842

.PARAMETER RisRoot
    The destination root -- the mapped RIS drive or UNC path. PENDING until the
    allocation exists, e.g. "R:\staging" or
    "\\storage1.ris.wustl.edu\<share>\staging".

.PARAMETER ArchiveRoot
    Defaults to the archive share. Z:\Gil\Shamir_1

.EXAMPLE
    .\stage_session_to_ris.ps1 -SessionId 20261021_111842 -RisRoot R:\staging
#>
param(
    [Parameter(Mandatory = $true)][string]$SessionId,
    [Parameter(Mandatory = $true)][string]$RisRoot,
    [string]$ArchiveRoot = "Z:\Gil\Shamir_1",
    [string]$MakeProbeMap = "D:\Gil\make_probe_map.py",
    [string]$PythonExe = "C:\Users\Adam\anaconda3\envs\kilosort4\python.exe",
    [switch]$MapOnly
)

$ErrorActionPreference = "Stop"

$srcSession  = Join-Path $ArchiveRoot "$SessionId.rec"
$srcKilosort = Join-Path $srcSession "$SessionId.kilosort"
$srcDio      = Join-Path $srcSession "$SessionId.DIO"
$dst         = Join-Path $RisRoot $SessionId

if (-not (Test-Path $srcKilosort)) {
    throw "No .kilosort folder at $srcKilosort -- is this session exported? Kilosort needs the trodesexport products, not the .rec."
}

Write-Host "session   $SessionId"
Write-Host "source    $srcSession"
Write-Host "dest      $dst"
Write-Host ""

# --- step 1: the probe map, generated HERE because the node cannot ----------
# make_probe_map.py reads the channelmap .dat from its CURRENT directory and
# writes the JSON beside it. It is run against a scratch copy rather than the
# archive, so the archive stays read-only.
$mapJson = Join-Path $srcKilosort "${SessionId}_custom_neuropixels_map.json"

if (Test-Path $mapJson) {
    Write-Host "[1/3] probe map already present in the archive:"
    Write-Host "      $mapJson"
} else {
    Write-Host "[1/3] generating the probe map (the node cannot do this -- no Trodes reader there)"
    $chanmap = Get-ChildItem $srcKilosort -Filter "*channelmap*.dat" -ErrorAction SilentlyContinue | Select-Object -First 1
    if (-not $chanmap) { throw "No channelmap .dat in $srcKilosort -- cannot build the probe map." }

    $work = Join-Path $env:TEMP "probemap_$SessionId"
    New-Item -ItemType Directory -Force -Path $work | Out-Null
    Copy-Item $chanmap.FullName -Destination $work -Force

    Push-Location $work
    try {
        & $PythonExe $MakeProbeMap
        if ($LASTEXITCODE -ne 0) { throw "make_probe_map.py exited $LASTEXITCODE" }
    } finally {
        Pop-Location
    }

    $built = Get-ChildItem $work -Filter "*_custom_neuropixels_map.json" | Select-Object -First 1
    if (-not $built) { throw "make_probe_map.py produced no JSON in $work" }
    $mapJson = $built.FullName
    Write-Host "      built $($built.Name) ($([math]::Round($built.Length/1KB,1)) KiB)"
}

# Sanity-check the map before a multi-day job is queued on it. The two channel
# maps in this project differ by a silent 820 um depth shift, so the y-range is
# printed: it is the only thing that distinguishes them by eye.
$map = Get-Content $mapJson -Raw | ConvertFrom-Json
$nchan = if ($map.n_chan) { $map.n_chan } else { $map.chanMap.Count }
$ycMin = ($map.yc | Measure-Object -Minimum).Minimum
$ycMax = ($map.yc | Measure-Object -Maximum).Maximum
Write-Host "      map: $nchan channels, yc $ycMin..$ycMax um"
if ($nchan -ne 384) { throw "probe map has $nchan channels, expected 384 -- wrong map for this recording." }
Write-Host "      ^ check that y-range against the session date (map A through 2026-10-23, map B from 2026-10-26)"
Write-Host ""

if ($MapOnly) { Write-Host "-MapOnly given; stopping before the copy."; exit 0 }

# --- step 2: free-space check before starting a 300 GiB copy ----------------
$probe1 = Get-ChildItem $srcKilosort -Filter "*.probe1.dat" | Select-Object -First 1
if (-not $probe1) { throw "No probe1.dat in $srcKilosort" }
$needGiB = [math]::Round(($probe1.Length + 3GB) / 1GB, 1)

New-Item -ItemType Directory -Force -Path $dst | Out-Null
$dstDrive = (Get-Item $dst).PSDrive
if ($dstDrive) {
    $freeGiB = [math]::Round($dstDrive.Free / 1GB, 1)
    Write-Host "[2/3] need ~$needGiB GiB, destination has $freeGiB GiB free"
    if ($freeGiB -lt $needGiB) {
        throw "Not enough room at $dst ($freeGiB GiB free, need ~$needGiB GiB). The RIS allocation holds about 5 sessions of input at a time -- clear a finished one first."
    }
} else {
    Write-Host "[2/3] destination is a UNC path; free space not checked automatically"
}
Write-Host ""

# --- step 3: copy ----------------------------------------------------------
# /J unbuffered for the big sequential file, no /NP so the log carries real
# percentages (destination file size is NOT progress -- robocopy preallocates).
Write-Host "[3/3] copying"
$log = Join-Path $env:TEMP "stage_${SessionId}.log"

$files = @("$SessionId.probe1.dat", "$SessionId.timestamps.dat") +
         (Get-ChildItem $srcKilosort -Filter "*channelmap*.dat" | ForEach-Object { $_.Name })

robocopy $srcKilosort $dst @files /J /R:2 /W:5 /TEE /LOG+:$log
if ($LASTEXITCODE -ge 8) { throw "robocopy failed with exit code $LASTEXITCODE (see $log)" }

# The map JSON, wherever it was built
Copy-Item $mapJson -Destination (Join-Path $dst (Split-Path $mapJson -Leaf)) -Force

# The DIO files, for the sync step
if (Test-Path $srcDio) {
    $dstDio = Join-Path $dst "DIO"
    New-Item -ItemType Directory -Force -Path $dstDio | Out-Null
    robocopy $srcDio $dstDio "*.dat" /R:2 /W:5 /NJH /NJS /LOG+:$log | Out-Null
    Write-Host "      DIO files copied"
}

Write-Host ""
Write-Host "staged. verify the big file matched before queueing a multi-day job:"
Write-Host "  source: $([math]::Round($probe1.Length/1GB,2)) GiB"
$dstProbe = Join-Path $dst $probe1.Name
if (Test-Path $dstProbe) {
    $d = (Get-Item $dstProbe).Length
    Write-Host "  dest:   $([math]::Round($d/1GB,2)) GiB"
    if ($d -ne $probe1.Length) {
        Write-Warning "SIZE MISMATCH -- do not sort this. Re-run the copy."
    } else {
        Write-Host "  sizes match."
    }
}
Write-Host ""
Write-Host "next: submit on a compute1 client with"
Write-Host "  bash ris_submit_kilosort.sh $SessionId <Th_universal> <Th_learned>"
Write-Host "  (the thresholds are per session -- 9.0/8.0 on 20260916, 9.2/7.0 on 20260910 and 20260901)"
